def build_description(desc, starter, cases):
    parts = [desc.strip()]
    parts.append("**كود البداية (C++):**")
    parts.append("```cpp\n" + starter.rstrip() + "\n```")
    parts.append("**أمثلة:**")
    for item in cases:
        inp, out = item[0], item[1]
        parts.append(f"```\nالمدخلات:\n{inp}\n\nالمخرجات:\n{out}\n```")
    return "\n\n".join(parts)


def main():
    sess = get_session()
    n = 0
    try:
        for key in sorted(AR.keys(), key=lambda k: int(k.split("-")[1])):
            ch = sess.query(Challenge).filter_by(challenge_key=key).first()
            if not ch:
                print("skip (not found):", key)
                continue
            title, desc = AR[key]
            s = SPECS[key]
            cases = [(s["inp"], s["out"])] + list(s.get("extra", []))
            ch.title = title
            ch.description = build_description(desc, CXX_STARTER, cases)
            n += 1
        sess.commit()
        print(f"Updated {n} challenges")
    finally:
        sess.close()


if __name__ == "__main__":
    main()
